// Package interfaces_and_type_assertions teaches interfaces and type assertions in Go.
//
// Interfaces are a powerful feature in Go that allow you to define behavior contracts.
// In Go, an interface is satisfied implicitly - if a type implements all the methods of an interface,
// it automatically implements that interface without needing to explicitly declare it.
//
// Type assertions let you extract the concrete value from an interface value.
// A type assertion takes an interface value and extracts from it the concrete value of a specified type.
